def _card(sl, x, y, w, h, kind, title, big, lines, *, big_size=26, foot=None):
    """큰 수치 하나를 앞세운 카드."""
    S.box(sl, x, y, w, h, [""], kind=kind)
    S.text(sl, x + 0.18, y + 0.11, w - 0.36, 0.24, title, size=12, bold=True)
    S.text(sl, x + 0.18, y + 0.45, w - 0.30, 0.46, big,
           size=big_size, bold=True, color=S.NAVY)
    for i, line in enumerate(lines):
        S.text(sl, x + 0.18, y + 1.12 + i * 0.235, w - 0.30, 0.20, line,
               size=9, wrap=True)
    if foot:
        S.rect(sl, x + 0.18, y + h - 0.40, w - 0.36, 0.01, S.KIND[kind][1])
        S.text(sl, x + 0.18, y + h - 0.32, w - 0.36, 0.20, foot,
               size=8.5, color=S.FOOT)


def _titled_box(sl, x, y, w, h, kind, title, lines, *, gap=0.235, size=9,
                title_color=None):
    S.box(sl, x, y, w, h, [""], kind=kind)
    S.text(sl, x + 0.18, y + 0.11, w - 0.36, 0.24, title, size=11.5, bold=True,
           color=title_color or S.BODY)
    for i, line in enumerate(lines):
        S.text(sl, x + 0.18, y + 0.46 + i * gap, w - 0.32, 0.20, line,
               size=size, wrap=True)


def _step(sl, x, y, w, h, top, bottom, *, hit=False):
    """평문 이름을 쓴 흐름 칸. hit이면 Qdrant가 닿는 칸이다."""
    if hit:
        shp = S.box(sl, x, y, w, h, [top, bottom], kind="store", size=9, bold=True)
        shp.line.color.rgb = S._rgb(S.NAVY)
        shp.line.width = Pt(2.25)
    else:
        shp = S.box(sl, x, y, w, h, [top, bottom], kind="self", size=9)
        shp.fill.fore_color.rgb = S._rgb("F4F4F4")
        shp.line.color.rgb = S._rgb("C4C4C4")
        for para in shp.text_frame.paragraphs:
            for run in para.runs:
                run.font.color.rgb = S._rgb("8A8A8A")
    return shp


def _bar(sl, lx, lw, bx, bw, y, frac, label, value, *, fill=None):
    S.text(sl, lx, y + 0.03, lw, 0.18, label, size=9)
    S.rect(sl, bx, y, bw, 0.20, "ECECEC")
    S.rect(sl, bx, y, max(0.05, bw * frac), 0.20, fill or S.STORE_L)
    S.text(sl, bx + bw + 0.12, y + 0.02, 1.25, 0.20, value,
           size=9.5, bold=True, font=S.MONO, color=S.CODE)


